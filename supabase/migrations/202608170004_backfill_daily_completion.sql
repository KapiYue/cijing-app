-- 历史「今日完成」回填（2026-08-17）
--
-- 背景：202608170001 把「完成」的判定从服务端硬编码规则（reading_count > 0 且
-- practice_count >= 5）改成「客户端走到练习总结页就调 complete_daily_session()」。
-- 新口径只对新产生的数据生效；而 202608170003 的连续天数只数 completed = true
-- 的日子，于是 1.0 期间攒下的历史活动日大多停在 false —— 不处理的话，老用户
-- 升级后连续天数会集体掉到 0~1。这不是数据丢失，是换口径的必然结果，但对用户
-- 而言观感等同于「我的记录被清零了」。
--
-- 历史数据里没有留下「有没有走到总结页」的任何痕迹，无法精确还原，只能用可观测
-- 的代理条件：**当天既读了短文、又答过题，就认为完成过一次学习**。
--   * 比旧规则宽：不再要求满 5 题。旧规则那个「5」本身就是个没有依据的魔法数字，
--     11.1 已经把它从代码库里删掉了，回填时自然也不该再拿它当标准；
--   * 比「有活动就算」严：只查了个词、没进练习的日子不会被算成完成。
--
-- 幂等：只改 completed = false 的行，重复执行没有额外效果。
-- 一次性数据迁移，只影响执行时点之前的存量行；此后由 complete_daily_session()
-- 负责置位。

update public.daily_activity
set completed = true
where completed = false
  and reading_count > 0
  and practice_count > 0;
